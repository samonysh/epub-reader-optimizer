"""Build standalone CSS templates from the upstream baseline + local rules.

Run after editing assets/translated.css or assets/reader-compat.css. Each
template is self-contained for readers that do not reliably support @import.
"""
from pathlib import Path


def sync_styles() -> None:
    assets = Path(__file__).resolve().parents[1] / "assets"
    baseline = (assets / "translated.css").read_text(encoding="utf-8")
    compat = (assets / "reader-compat.css").read_text(encoding="utf-8")
    combined = "/* Generated by scripts/sync_styles.py; edit the source assets. */\n" + baseline + "\n" + compat
    (assets / "stylesheet.template.css").write_text(combined, encoding="utf-8")
    fonts = '''
/* Optional embedded fonts for formula-image books. Place this stylesheet in
   Styles/ and register Fonts/*.woff2 in the OPF; adjust paths when needed.
   Download/subset fonts separately: these declarations do not bundle files. */
@font-face {
  font-family: "LXGW WenKai";
  src: url("../Fonts/LXGWWenKai.woff2") format("woff2");
}
@font-face {
  font-family: "LXGW WenKai Mono";
  src: url("../Fonts/LXGWWenKaiMono.woff2") format("woff2");
}
body { font-family: "LXGW WenKai", "霞鹜文楷", Georgia, "Noto Serif CJK SC", serif !important; }
pre, code, kbd, samp, tt, .reading-code-block,
.EmphasisFontCategoryNonProportional, .emphasisfontcategorynonproportional {
  font-family: "LXGW WenKai Mono", "霞鹜文楷等宽", Consolas, monospace !important;
}
'''
    (assets / "stylesheet.formula-image.css").write_text(combined + fonts, encoding="utf-8")


if __name__ == "__main__":
    sync_styles()
